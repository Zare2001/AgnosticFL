"""Peak memory on the central machine during the stage-2 payload sweep (docs tooling; writes only under docs/).

    python scripts/docs/central_memory.py [--runs ~/flhub-runtime/runs/stage2]

Reads `sysmon/central.json` (scripts/sysmon.py; "MB" there is MiB) of every E4a run directory
`s2-e4a-<scope>-<size>mb-latest` and writes docs/results/evidence/stage2/central-e4a-memory.md:
peak RSS per process in MiB, for the processes of the run's scope plus the orchestrator and the
hub core, and the peak memory in use on the whole machine. Long-lived processes of the other
frameworks are left out: they keep memory from their own earlier runs.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "results" / "evidence" / "stage2" / "central-e4a-memory.md"
HUB = [("orchestrator", "orchestrator"), ("hub-core", "hub core")]
SCOPE_PROCS = {
    "nvflare": [("nvflare-server-job", "NVFlare relay job"), ("nvflare-server", "NVFlare server"),
                ("adapter-nvflare", "NVFlare adapter")],
    "flower": [("flower-serverapp", "Flower relay ServerApp"), ("flower-superlink", "Flower SuperLink"),
               ("adapter-flower", "Flower adapter")],
    "vantage6": [("v6-server", "vantage6 server"), ("adapter-vantage6", "vantage6 adapter")],
}
SCOPE_PROCS["mixed"] = [SCOPE_PROCS["nvflare"][0], SCOPE_PROCS["flower"][0], SCOPE_PROCS["vantage6"][0],
                        SCOPE_PROCS["vantage6"][1]]


def runs_by_scope(root: Path) -> dict[str, list[tuple[int, Path]]]:
    found: dict[str, list[tuple[int, Path]]] = {}
    for link in root.glob("s2-e4a-*-latest"):
        m = re.fullmatch(r"s2-e4a-(\w+)-(\d+)mb-latest", link.name)
        if m:
            found.setdefault(m.group(1), []).append((int(m.group(2)), link.resolve()))
    return {k: sorted(v) for k, v in found.items()}


def cell(mib: float | None, size: int) -> str:
    if mib is None:
        return "-"
    return f"{mib:,.0f} ({mib / size:.1f}x)" if size >= 32 else f"{mib:,.0f}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="scripts/docs/central_memory.py")
    ap.add_argument("--runs", default="~/flhub-runtime/runs/stage2")
    args = ap.parse_args(argv)
    found = runs_by_scope(Path(args.runs).expanduser())
    out = ["# Central machine: peak memory during the payload sweep E4a (generated by scripts/docs/central_memory.py)",
           "", "Source: `sysmon/central.json` of each E4a run directory on the central VM (`scripts/sysmon.py`, "
           "sampled every second; its \"MB\" is MiB). Peak RSS per process in MiB; from 32 MiB on, the factor "
           "in brackets is peak RSS / payload. *used* = peak memory in use on the whole machine (31.3 GiB "
           "RAM). Each table lists the processes of its scope plus the orchestrator and the hub core; "
           "long-lived processes of the other frameworks keep memory from their own earlier runs and are "
           "left out. Payload sizes are MiB per site and direction (`payload-<N>` echo model, 2 sites per "
           "framework).", ""]
    for scope in ("nvflare", "flower", "vantage6", "mixed"):
        procs = HUB + SCOPE_PROCS[scope]
        out += [f"## {scope}", "",
                "| payload MiB | status | " + " | ".join(label for _, label in procs) + " | used MiB |",
                "|---" * (len(procs) + 3) + "|"]
        for size, rd in found.get(scope, []):
            data = json.loads((rd / "sysmon" / "central.json").read_text())
            peak = {name: p.get("rss_mb_peak") for name, p in data["procs"].items()}
            status = "finalized" if (rd / "finalized.json").exists() else "not delivered (limit)"
            cells = [cell(peak.get(name), size) for name, _ in procs]
            used = data["system"]["mem_used_mb_peak"]
            out.append(f"| {size} | {status} | " + " | ".join(cells) + f" | {used:,.0f} |")
        if scope == "mixed":
            out += ["", "The NVFlare relay job is one long-running process: in the mixed runs it still held about 2,000 MiB "
                        "from the NVFlare-only sweep before them, so its mixed values are upper bounds and their factors "
                        "say nothing about the payload."]
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
