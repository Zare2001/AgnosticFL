"""Markdown tables for REPORT_STAGE2.md, computed from the run dirs (no hand-copied numbers).

    python scripts/stage2/report_tables.py [--runs ~/flhub-runtime/runs/stage2] [--out docs/report/stage2/tables.md]

Sections: E1, E2 (mean ± sd over seeds 2026 real + 2027/2028 sim, rounds-to-target), E3 round-time
breakdown, E4a, E4b, E5, E6, E7. Tables whose runs are missing say so.
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

RUNS = Path.home() / "flhub-runtime" / "runs" / "stage2"
OUT = Path(__file__).resolve().parents[2] / "docs" / "report" / "stage2" / "tables.md"
PIDS = ["iid", "dir1.0", "dir0.3", "dir0.1", "qty", "fwcorr", "mix"]
AGGS = ["fedavg", "fedavgm", "fedadam", "fedyogi", "fedadagrad", "fedprox"]
FWS = ["nvflare", "vantage6", "flower"]
PREFIX = {"nvf": "nvflare", "v6": "vantage6", "flw": "flower"}


def load(name: str) -> dict | None:
    p = RUNS / f"{name}-latest"
    if not p.exists():
        return None
    p = p.resolve()
    rows = [json.loads(x) for x in (p / "metrics.jsonl").read_text().splitlines() if x.strip()] \
        if (p / "metrics.jsonl").exists() else []
    summ = json.loads((p / "summary.json").read_text()) if (p / "summary.json").exists() else {}
    return {"path": p, "rows": rows, "summary": summ}


def last(run: dict | None, key: str):
    if not run:
        return None
    vals = [r[key] for r in run["rows"] if key in r]
    return vals[-1] if vals else None


def fmt(v, nd=3, pct=False) -> str:
    if v is None:
        return "-"
    return f"{100 * v:.1f}" if pct else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def ms(vals: list[float], pct=True) -> str:
    vals = [v for v in vals if v is not None]
    if not vals:
        return "-"
    m = statistics.mean(vals)
    if len(vals) == 1:
        return f"{100 * m:.1f}" if pct else f"{m:.3f}"
    sd = statistics.stdev(vals)
    return f"{100 * m:.1f} ± {100 * sd:.1f}" if pct else f"{m:.3f} ± {sd:.3f}"


def seeds(name: str) -> list[dict]:
    return [r for r in (load(name), load(f"{name}-seed2027"), load(f"{name}-seed2028")) if r]


def rounds_to_target(run: dict | None, target: float | None):
    if not run or target is None:
        return None
    for r in run["rows"]:
        if r.get("step", 0) > 0 and r.get("global/test_acc", 0) >= target:
            return r["step"]
    return "not reached"


def med(vals):
    vals = [v for v in vals if v is not None]
    return statistics.median(vals) if vals else None


def rounds2(run: dict) -> list[dict]:
    return [r for r in run["rows"] if r.get("step", 0) >= 2 and "round/duration_s" in r]


def fw_mean(row: dict, suffix: str, fw: str):
    vals = [v for k, v in row.items() if k.startswith("site/") and k.endswith("/" + suffix)
            and PREFIX.get(k.split("/")[1].split("-")[0]) == fw]
    return statistics.mean(vals) if vals else None


def learning_table(title: str, names: list[tuple[str, str]], target: float | None) -> list[str]:
    out = [f"### {title}", "", "| run | n seeds | test acc % | bal acc % | macro AUC % | worst-site acc % | "
           "site-shaped sd | rounds-to-target (seed 2026) |", "|---|---|---|---|---|---|---|---|"]
    for label, name in names:
        rs = seeds(name)
        if not rs:
            out.append(f"| {label} | 0 | - | - | - | - | - | - |")
            continue
        out.append(f"| {label} | {len(rs)} | {ms([last(r, 'global/test_acc') for r in rs])} | "
                   f"{ms([last(r, 'global/test_bal_acc') for r in rs])} | {ms([last(r, 'global/test_auc') for r in rs])} | "
                   f"{ms([last(r, 'siteshaped/min_acc') for r in rs])} | "
                   f"{ms([last(r, 'siteshaped/std_acc') for r in rs], pct=False)} | {rounds_to_target(rs[0], target)} |")
    return out + [""]


def main(argv: list[str] | None = None) -> int:
    global RUNS
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(RUNS))
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    RUNS = Path(args.runs).expanduser()
    lines = ["# Stage 2 — result tables (generated by scripts/stage2/report_tables.py)", ""]
    cen = load("s2-e1-centralized")
    cen_acc = last(cen, "global/test_acc")
    target = 0.95 * cen_acc if cen_acc else None
    lines += [f"Centralized reference (`s2-e1-centralized`): final test accuracy {fmt(cen_acc, pct=True)} %; "
              f"target for rounds-to-target = 0.95 × that = {fmt(target, pct=True)} %.", ""]
    for pid in ("iid", "dir0.1"):
        loc = load(f"s2-e1-local-{pid}")
        if loc:
            lines.append(f"Local-only `{pid}`: mean site test accuracy {fmt(last(loc, 'local/mean_acc'), pct=True)} %, "
                         f"min {fmt(last(loc, 'local/min_acc'), pct=True)} %, max {fmt(last(loc, 'local/max_acc'), pct=True)} %.")
    lines.append("")
    lines += learning_table("E1 — FedAvg per partition (seed 2026 real; 2027/2028 hub.sim)",
                            [(pid, f"s2-e1-{pid}-fedavg") for pid in PIDS], target)
    for pid in ("iid", "dir0.3", "dir0.1"):
        lines += learning_table(f"E2 — aggregators on {pid}",
                                [(a, f"s2-e1-{pid}-fedavg" if a == "fedavg" else f"s2-e2-{pid}-{a}") for a in AGGS],
                                target)
    # E3
    lines += ["### E3 — round-time breakdown (median over rounds >= 2; seconds)", "",
              "| run | params | framework | train | overhead | fan-out | hub agg | hub eval | round | test acc % |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for name in ["s2-e1-dir0.3-fedavg", "s2-e2-dir0.3-fedavgm", "s2-e3-cnn-medium-fedavg", "s2-e3-cnn-medium-fedavgm",
                 "s2-e3-resnet18-gn-fedavg", "s2-e3-resnet18-gn-fedavgm"]:
        run = load(name)
        if not run:
            lines.append(f"| {name} | - | - | - | - | - | - | - | - | - |")
            continue
        rows = rounds2(run)
        cfg = json.loads((run["path"] / "config.json").read_text())
        for fw in FWS:
            lines.append(f"| {name} | {cfg.get('model_params')} | {fw} | {fmt(med([fw_mean(r, 'train_time_s', fw) for r in rows]), 2)} | "
                         f"{fmt(med([fw_mean(r, 'overhead_s', fw) for r in rows]), 2)} | "
                         f"{fmt(med([r.get(f'adapter/{fw}/fanout_s') for r in rows]), 2)} | "
                         f"{fmt(med([r['round/agg_s'] for r in rows]), 3)} | {fmt(med([r['round/eval_s'] for r in rows]), 2)} | "
                         f"{fmt(med([r['round/duration_s'] for r in rows]), 2)} | {fmt(last(run, 'global/test_acc'), pct=True)} |")
    lines.append("")
    # E4a
    lines += ["### E4a — payload sweep (median of rounds 2-3)", "",
              "| scope | MiB | status | round s | per-framework fan-out s | INV-1 |", "|---|---|---|---|---|---|"]
    for scope in FWS + ["mixed"]:
        for size in [1, 8, 32, 64, 128, 256, 512, 1024]:
            run = load(f"s2-e4a-{scope}-{size}mb")
            if not run:
                continue
            rows = rounds2(run)
            inv = run["path"] / "inv1.json"
            inv1 = json.loads(inv.read_text()).get("hashes_equal") if inv.exists() else None
            fan = ", ".join(f"{fw} {fmt(med([r.get(f'adapter/{fw}/fanout_s') for r in rows]), 1)}" for fw in FWS
                            if any(f"adapter/{fw}/fanout_s" in r for r in rows))
            lines.append(f"| {scope} | {size} | {run['summary'].get('status', '?')} | "
                         f"{fmt(med([r['round/duration_s'] for r in rows]), 1)} | {fan or '-'} | "
                         f"{'hashes equal' if inv1 else ('-' if inv1 is None else 'FAIL')} |")
    lines.append("")
    # E4b, E5, E7 (fan-out medians)
    lines += ["### E4b — bandwidth (payload-45, mixed)", "", "| profile | round s | nvflare fan-out | vantage6 | flower |",
              "|---|---|---|---|---|"]
    for p in ["none", "wan1g", "wan100", "wan20"]:
        run = load(f"s2-e4b-{p}")
        if run:
            rows = rounds2(run)
            lines.append(f"| {p} | {fmt(med([r['round/duration_s'] for r in rows]), 1)} | " + " | ".join(
                fmt(med([r.get(f'adapter/{fw}/fanout_s') for r in rows]), 1) for fw in FWS) + " |")
    lines += ["", "### E5 — number of sites", "", "| run | round s | nvflare fan-out | vantage6 | flower | test acc % |",
              "|---|---|---|---|---|---|"]
    for n in ("6sites", "12sites"):
        run = load(f"s2-e5-{n}")
        if run:
            rows = rounds2(run)
            lines.append(f"| s2-e5-{n} | {fmt(med([r['round/duration_s'] for r in rows]), 1)} | " + " | ".join(
                fmt(med([r.get(f'adapter/{fw}/fanout_s') for r in rows]), 1) for fw in FWS) +
                f" | {fmt(last(run, 'global/test_acc'), pct=True)} |")
    lines += ["", "### E6 — robustness", "", "| run | rounds | retried rounds | dropped site-rounds | resumed | final acc % |",
              "|---|---|---|---|---|---|"]
    for name in ["s2-e6a-strict", "s2-e6a-minsites", "s2-e6b-straggler", "s2-e6c-fedavg", "s2-e6c-fedavgm",
                 "s2-e6d-resume", "s2-e6e-server-restart"]:
        run = load(name)
        if run:
            s = run["summary"]
            lines.append(f"| {name} | {s.get('rounds')} | {s.get('retries_total')} | {s.get('dropped_sites_total')} | "
                         f"{s.get('resumed')} | {fmt(s.get('final/test_acc'), pct=True)} |")
    lines += ["", "### E7 — native FedAvg vs hub (median round s, rounds >= 2)", "",
              "| framework | config | native | hub | overhead s | overhead % |", "|---|---|---|---|---|---|"]
    for fw in FWS:
        for c in ("cnn", "payload"):
            nat, hub = load(f"s2-e7-{fw}-native-{c}"), load(f"s2-e7-{fw}-hub-{c}")
            if nat and hub:
                a = med([r.get("round/duration_s") for r in rounds2(nat)])
                b = med([r["round/duration_s"] for r in rounds2(hub)])
                ov = (b - a) if a and b else None
                lines.append(f"| {fw} | {c} | {fmt(a, 2)} | {fmt(b, 2)} | {fmt(ov, 2)} | "
                             f"{fmt(100 * ov / a if ov is not None and a else None, 1)} |")
    # RQ1: INV-1 per final real run (from runs.md, which finalize_run.py fills after the gate passed)
    runs_md = Path(__file__).resolve().parents[2] / "docs" / "report" / "stage2" / "runs.md"
    rows = [[c.strip() for c in x.strip().strip("|").split("|")] for x in runs_md.read_text().splitlines()
            if x.startswith("| s2-")]
    real = [r for r in rows if r[2] == "real"]
    by_method = {}
    for r in real:
        by_method.setdefault(r[9].split(":")[0], []).append(r)
    lines += ["", "### RQ1 — INV-1 for every final real run", "",
              f"{len(real)} real runs finalized; methods: " + ", ".join(f"{k} {len(v)}" for k, v in by_method.items())
              + f"; max inv1_max_diff over all: {max((float(r[10]) for r in real if r[10] not in ('-', '')), default=0.0):.3g}.",
              "", "| run | exp | method | max abs diff |", "|---|---|---|---|"]
    lines += [f"| {r[0]} | {r[1]} | {r[9]} | {r[10]} |" for r in real]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
