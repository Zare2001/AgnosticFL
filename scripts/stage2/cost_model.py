"""Round-time cost model for RQ4 (REPORT_TEMPLATE §6): round_time ≈ a + b·payload + max_k train_k.

    python scripts/stage2/cost_model.py [--out docs/results/evidence/stage2/cost_model.md]

Per framework, least squares on relative residuals on the E4a single-framework sweeps (echo training, train ≈ 0): fan-out
time (dispatch to the last result of the framework's two sites; median of rounds 2-3) = a + b · P,
with P the payload in MiB. vantage6 grows superlinearly beyond 64 MiB (its server is CPU-bound in one process), so
its predictions use the linear fit on 1-64 MiB (the learning models are <= 43 MiB); a quadratic fit
a + b·P + c·P² over all sizes is reported for every framework. The fits then predict the fan-out of every learning run
with real training (E3; E1 and E2 dir0.3 for cnn-small) as fit(P_model) + max over the framework's
sites of train_time_s, and of the E4b runs (payload-45 under netem) as fit(P) + V·P/rate, V = the payloads
a framework moves per VM link and round (4 for NVFlare and Flower: two sites, download before training and
upload after it; 17.8 for vantage6, which sends each input four times, double base64). Reported: coefficients, R², and
the prediction error per run (median over rounds >= 2).
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
RUNS = Path.home() / "flhub-runtime" / "runs" / "stage2"
OUT = REPO / "docs" / "results" / "evidence" / "stage2" / "cost_model.md"
FWS = ["nvflare", "vantage6", "flower"]
SIZES = [1, 8, 32, 64, 128, 256, 512]
PREFIX = {"nvflare": "nvf-", "vantage6": "v6-", "flower": "flw-"}
MODEL_MB = {"cnn-small": 52203 * 4 / 2**20, "cnn-medium": 1676779 * 4 / 2**20, "resnet18-gn": 11173323 * 4 / 2**20}
RATE_MBPS = {"wan1g": 1000, "wan100": 100, "wan20": 20}  # Mbit/s
VOLUME = {"nvflare": 4.0, "flower": 4.0, "vantage6": 17.8}  # payloads per VM link and round (see the E4b note)
LEARNING = ["s2-e1-dir0.3-fedavg", "s2-e2-dir0.3-fedavgm", "s2-e3-cnn-medium-fedavg", "s2-e3-cnn-medium-fedavgm",
            "s2-e3-resnet18-gn-fedavg", "s2-e3-resnet18-gn-fedavgm"]


def rows(name: str) -> list[dict]:
    link = RUNS / f"{name}-latest"
    if not link.exists():
        return []
    return [json.loads(x) for x in (link.resolve() / "metrics.jsonl").read_text().splitlines()]


def fanout(r: dict, fw: str) -> float | None:
    return r.get(f"adapter/{fw}/fanout_s")


def max_train(r: dict, fw: str) -> float | None:
    vals = [v for k, v in r.items() if k.startswith(f"site/{PREFIX[fw]}") and k.endswith("/train_time_s")]
    return max(vals) if vals else None


def median_rounds(name: str, fn, first: int = 2) -> float | None:
    vals = [v for r in rows(name) if r.get("step", 0) >= first and (v := fn(r)) is not None]
    return statistics.median(vals) if vals else None


def fit(x: list[float], y: list[float], deg: int) -> tuple[np.ndarray, float]:
    # relative residuals (w = 1/y): sizes span 1-256 MiB, an unweighted fit would ignore the small ones
    coef = np.polyfit(x, y, deg, w=1 / np.array(y))
    pred = np.polyval(coef, x)
    ss_res = float(np.sum((np.array(y) - pred) ** 2))
    ss_tot = float(np.sum((np.array(y) - np.mean(y)) ** 2))
    return coef, 1 - ss_res / ss_tot if ss_tot else float("nan")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    lines = ["# Round-time cost model (generated by scripts/stage2/cost_model.py)", "",
             "Fit on the E4a single-framework sweeps (echo training): fan-out time per round = a + b·P (P in MiB), "
             "median of rounds 2-3.", "",
             "| framework | sizes (MiB) | a (s) | b (s/MiB) | R² | quadratic c (s/MiB²) | R² (quadratic) |",
             "|---|---|---|---|---|---|---|"]
    fits = {}
    for fw in FWS:
        pts = [(s, t) for s in SIZES if (t := median_rounds(f"s2-e4a-{fw}-{s}mb", lambda r: fanout(r, fw))) is not None]
        if len(pts) < 3:
            continue
        x, y = [p[0] for p in pts], [p[1] for p in pts]
        (b, a), r2 = fit(x, y, 1)
        (c2, b2, a2), r2q = fit(x, y, 2)
        fits[fw] = {"lin": (a, b), "r2": r2}
        lines.append(f"| {fw} | {','.join(str(s) for s in x)} | {a:.2f} | {b:.4f} | {r2:.3f} | {c2:.2e} | {r2q:.3f} |")
        if fw == "vantage6":  # superlinear beyond 64 MiB: the learning models (<= 43 MiB) use the 1-64 MiB fit
            xs, ys = [v for v in x if v <= 64], [t for v, t in zip(x, y) if v <= 64]
            (b, a), r2 = fit(xs, ys, 1)
            fits[fw] = {"lin": (a, b), "r2": r2}
            lines.append(f"| vantage6 (1-64 MiB, used below) | {','.join(str(s) for s in xs)} | {a:.2f} | {b:.4f} | "
                         f"{r2:.3f} | | |")
    lines += ["", "Prediction for runs with real training: fan-out ≈ a + b·P_model + max_k train_k "
              "(linear fits; vantage6 on 1-64 MiB). Median over rounds >= 2.", "",
              "| run | framework | P (MiB) | max train (s) | predicted (s) | measured (s) | error |",
              "|---|---|---|---|---|---|---|"]

    def predict(fw: str, p: float) -> float:
        a, b = fits[fw]["lin"]
        return a + b * p

    for name in LEARNING:
        cfg = RUNS / f"{name}-latest" / "config.json"
        if not cfg.exists():
            continue
        model = json.loads(cfg.read_text()).get("model")
        p = MODEL_MB.get(model)
        for fw in FWS:
            if fw not in fits or p is None:
                continue
            tr = median_rounds(name, lambda r: max_train(r, fw))
            meas = median_rounds(name, lambda r: fanout(r, fw))
            if tr is None or meas is None:
                continue
            pred = predict(fw, p) + tr
            lines.append(f"| {name} | {fw} | {p:.1f} | {tr:.1f} | {pred:.1f} | {meas:.1f} | "
                         f"{(pred - meas) / meas * 100:+.0f} % |")
    lines += ["", "E4b (payload-45, mixed scope, netem on both ends): fan-out ≈ fit(45) + V·P/rate, with V the bytes a "
              "framework moves per VM link and round in units of P: 4 for NVFlare and Flower (2 sites, each P down and P "
              "up), 17.8 for vantage6 (2 sites x (4 input copies down + 1 result up) x 1.78 for double base64; "
              "vantage6 section §4). Efficiency = plan lower bound 4·P/rate ÷ measured.", "",
              "| profile | framework | lower bound 4·P/rate (s) | V·P/rate (s) | predicted (s) | measured (s) | error | "
              "efficiency |", "|---|---|---|---|---|---|---|---|"]
    for prof in ["none", "wan1g", "wan100", "wan20"]:
        name = f"s2-e4b-{prof}"
        if not (RUNS / f"{name}-latest").exists():
            continue
        p = 45.0
        for fw in FWS:
            if fw not in fits:
                continue
            meas = median_rounds(name, lambda r: fanout(r, fw))
            if meas is None:
                continue
            lb = 4 * p * 8 * 2**20 / (RATE_MBPS[prof] * 1e6) if prof in RATE_MBPS else 0.0
            vol = VOLUME[fw] * p * 8 * 2**20 / (RATE_MBPS[prof] * 1e6) if prof in RATE_MBPS else 0.0
            pred = predict(fw, p) + vol
            lines.append(f"| {prof} | {fw} | {lb:.1f} | {vol:.1f} | {pred:.1f} | {meas:.1f} | "
                         f"{(pred - meas) / meas * 100:+.0f} % | {lb / meas:.2f} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
