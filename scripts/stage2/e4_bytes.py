"""Bytes on wire per framework for E4 runs (PLAN.md stage 2 §4.3): sysmon interface deltas.

    python scripts/stage2/e4_bytes.py [--runs ~/flhub-runtime/runs/stage2] [--out docs/results/evidence/stage2/e4_bytes.md]

For every E4a/E4b/E7-payload run with sysmon summaries from the framework VMs: rx/tx bytes of the
VM's main interface over the run window, the payload the protocol had to move (sites on that VM x
2 directions x rounds x payload MiB), and the overhead ratio bytes / payload. The VM of a framework
that has no site in the run gives the background traffic (bus, SSH, heartbeats) for that window.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

RUNS = Path.home() / "flhub-runtime" / "runs" / "stage2"
OUT = Path(__file__).resolve().parents[2] / "docs" / "results" / "evidence" / "stage2" / "e4_bytes.md"
FWS = {"nvflare": "nvf", "vantage6": "v6", "flower": "flw"}


def vm_summary(run_dir: Path, fw: str) -> dict | None:
    """The summary sent by that framework VM's follower: <run>-nvflare-sysmon.json or sysmon-<fw>-<run>.json."""
    for f in sorted((run_dir / "sysmon").glob("*.json")):
        if f.name.endswith(f"-{fw}-sysmon.json") or f.name.startswith(f"sysmon-{fw}-"):
            return json.loads(f.read_text())
    return None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(RUNS))
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    root = Path(args.runs).expanduser()
    lines = ["# E4 — bytes on wire per framework VM (generated by scripts/stage2/e4_bytes.py)", "",
             "Interface byte deltas (rx = from central, tx = to central) over the run window; payload = sites on "
             "that VM × 2 directions × rounds × size. Ratio = (rx + tx) / payload.", "",
             "| run | framework | sites | rounds | payload MiB | rx MiB | tx MiB | ratio | background (idle VM) MiB |",
             "|---|---|---|---|---|---|---|---|---|"]
    for link in sorted(root.glob("s2-e[47]*-latest")):
        run_dir = link.resolve()
        cfg_p = run_dir / "config.json"
        if not cfg_p.exists():
            continue
        cfg = json.loads(cfg_p.read_text())
        model = cfg.get("model", "")
        if not model.startswith("payload-"):
            continue
        size = float(model.split("-")[1])
        sites = list((cfg.get("sites") or {}).keys())
        rounds = cfg.get("rounds", 0)
        idle = [fw for fw, p in FWS.items() if not any(s.startswith(p + "-") for s in sites)]
        bg = None
        for fw in idle:
            s = vm_summary(run_dir, fw)
            if s and s.get("net"):
                n = s["net"].get(s.get("main_iface") or "ens3") or next(iter(s["net"].values()))
                bg = (n["rx_bytes"] + n["tx_bytes"]) / 2**20
                break
        for fw, prefix in FWS.items():
            mine = [x for x in sites if x.startswith(prefix + "-")]
            s = vm_summary(run_dir, fw)
            if not mine or not s or not s.get("net"):
                continue
            n = s["net"].get(s.get("main_iface") or "ens3") or next(iter(s["net"].values()))
            rx, tx = n["rx_bytes"] / 2**20, n["tx_bytes"] / 2**20
            payload = len(mine) * 2 * rounds * size
            lines.append(f"| {cfg.get('run_name', link.name)} | {fw} | {len(mine)} | {rounds} | {payload:.0f} | "
                         f"{rx:.1f} | {tx:.1f} | {(rx + tx) / payload:.3f} | {'-' if bg is None else f'{bg:.1f}'} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} ({len(lines) - 6} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
