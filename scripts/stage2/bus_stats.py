"""Collaboration statistics for REPORT_STAGE2.md §10: milestones, bus traffic, commits.

    python scripts/stage2/bus_stats.py [--since 98] [--out docs/report/stage2/collaboration.md]

Reads the stage-2 bus log (messages after STAGE2-START, #98) and the git history since
stage1-final. Writes a Markdown file with the S-milestone timeline, message counts by type
and sender, RUNLOCK grants, and commits per scope and per agent role.
"""

from __future__ import annotations

import argparse
import collections
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MSG = re.compile(r"^#(\d+) (\S+) \[([\w-]+)\] (\S+) -> (\S+): (.*)$")


def bus_log(since: int) -> list[dict]:
    out = subprocess.run([str(REPO / "tools" / "bus"), "log", "--since", str(since), "--limit", "100000"],
                         cwd=REPO, capture_output=True, text=True).stdout
    msgs = []
    for line in out.splitlines():
        m = MSG.match(line)
        if m:
            msgs.append({"id": int(m.group(1)), "ts": m.group(2), "type": m.group(3), "from": m.group(4),
                         "to": m.group(5), "subject": m.group(6)})
    return msgs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--since", type=int, default=97)
    ap.add_argument("--out", default=str(REPO / "docs" / "report" / "stage2" / "collaboration.md"))
    args = ap.parse_args(argv)
    msgs = bus_log(args.since)
    lines = ["# Stage 2 — collaboration statistics (generated by scripts/stage2/bus_stats.py)", "",
             f"Bus messages #{msgs[0]['id'] if msgs else '-'} .. #{msgs[-1]['id'] if msgs else '-'}: {len(msgs)}.", "",
             "## Milestones", "", "| # | UTC | from | milestone |", "|---|---|---|---|"]
    for m in msgs:
        if m["type"] == "milestone":
            lines.append(f"| {m['id']} | {m['ts'][:19]}Z | {m['from']} | {m['subject']} |")
    by_type = collections.Counter(m["type"] for m in msgs)
    by_from = collections.Counter(m["from"] for m in msgs)
    lines += ["", "## Messages by type", "", "| type | count |", "|---|---|"]
    lines += [f"| {t} | {n} |" for t, n in by_type.most_common()]
    lines += ["", "## Messages by sender", "", "| sender | count |", "|---|---|"]
    lines += [f"| {f} | {n} |" for f, n in by_from.most_common()]
    locks = [m for m in msgs if "RUNLOCK" in m["subject"]]
    lines += ["", f"RUNLOCK messages: {len(locks)} (acquire/granted/release).", ""]
    log = subprocess.run(["git", "-C", str(REPO), "log", "stage1-final..HEAD", "--format=%s"], capture_output=True,
                         text=True).stdout.splitlines()
    scopes = collections.Counter(s.split(":", 1)[0] for s in log if ":" in s)
    lines += ["## Commits since stage1-final", "", f"Total: {len(log)}.", "", "| scope | commits |", "|---|---|"]
    lines += [f"| {s} | {n} |" for s, n in scopes.most_common()]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {len(msgs)} messages, {len(log)} commits")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
